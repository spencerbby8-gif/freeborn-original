import { chromium } from "playwright";
import fs from "node:fs";
const BASE = "https://3000-i6gipzc6qr7oablffprmu.e2b.app";
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 } });
const page = await ctx.newPage();
const logs = [];
page.on("response", (r) => { if (r.url().includes("/api/onboarding/state")) logs.push(`[state] ${r.status()}`); });
await page.goto(`${BASE}/auth?mode=sign-in`, { waitUntil: "domcontentloaded", timeout: 40000 });
await page.locator('input[id="email"]').fill("e2e-nav@freeborn.app");
await page.locator('input[id="password"]').fill("E2eNav2026x");
await page.locator('button[type="submit"]').click();
await page.waitForURL("**/app", { timeout: 25000 }).catch(() => {});
const url = page.url();
const tabs = await page.locator("nav.fixed.inset-x-0.bottom-0 a").count().catch(() => 0);
const deck = await page.locator("article").count().catch(() => 0);
console.log(url.includes("/app") && tabs === 5 ? `PASS | completed member -> /app (tabs=${tabs}, deck cards=${deck})` : `FAIL | url=${url} tabs=${tabs}`);
console.log("state calls:", logs.join(" ") || "none");
await browser.close();
