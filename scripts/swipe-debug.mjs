import { chromium } from "playwright";
import fs from "node:fs";
const BASE = "https://3000-ixb2zvxuhd5nos32g83n2.e2b.app";
const token = fs.readFileSync("/tmp/vttok.txt","utf8").trim();
const vid = fs.readFileSync("/tmp/vtid.txt","utf8").trim();
const session = JSON.stringify({ access_token: token, token_type:"bearer", expires_at: Math.floor(Date.now()/1000)+3600, expires_in:3600, refresh_token:"e2e", user:{ id: vid, aud:"authenticated", role:"authenticated", email:"verify-test@freeborn.app", app_metadata:{}, user_metadata:{}, created_at:"2026-10-05T21:00:00Z", updated_at:"2026-10-05T21:00:00Z" }});
const browser = await chromium.launch({ args:["--no-sandbox"] });
const ctx = await browser.newContext({ viewport:{width:420,height:900} });
await ctx.addInitScript(([k,v])=>localStorage.setItem(k,v), ["sb-ihwtpwlszegrjgakqsxx-auth-token", session]);
const page = await ctx.newPage();
page.setDefaultTimeout(9000);
const likesCalls=[];
page.on("request", r => { if(r.url().includes("/api/likes")) likesCalls.push(`${r.method()} ${r.url().slice(-40)}`); });
page.on("console", m => { if(m.type()==="error") console.log("[console-err]", m.text().slice(0,100)); });
await page.goto(`${BASE}/app`, { waitUntil:"domcontentloaded", timeout:30000 });
await page.waitForSelector("article", { timeout:20000 });
await page.waitForTimeout(1200);
const name = await page.locator("article h2").first().textContent().catch(()=>"");
console.log("first card:", name.trim());
const box = await page.locator("article").first().boundingBox();
console.log("card box:", Math.round(box.x), Math.round(box.y), Math.round(box.width), Math.round(box.height));
// swipe on photo area
await page.mouse.move(box.x+box.width*0.5, box.y+box.height*0.28);
await page.mouse.down();
for(let i=1;i<=10;i++){ await page.mouse.move(box.x+box.width*0.5 - i*20, box.y+box.height*0.28); await page.waitForTimeout(30); }
await page.mouse.up();
await page.waitForTimeout(1500);
console.log("likes calls during swipe:", likesCalls.length ? likesCalls.join(", ") : "NONE");
const name2 = await page.locator("article h2").first().textContent().catch(()=>"EMPTY");
console.log("after swipe:", (name2||"").trim()||"EMPTY");
await browser.close();
process.exit(0);
